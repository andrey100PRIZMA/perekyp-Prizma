-- Минимальная схема для облачного сохранения и промокодов.
create table if not exists public.profiles (id uuid primary key references auth.users(id) on delete cascade, role text not null default 'player');
alter table public.profiles enable row level security;
drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select using (auth.uid()=id);

create table if not exists public.game_saves (user_id uuid primary key references auth.users(id) on delete cascade, save_data jsonb not null default '{}'::jsonb, updated_at timestamptz not null default now());
alter table public.game_saves enable row level security;
drop policy if exists "users read own save" on public.game_saves;
drop policy if exists "users insert own save" on public.game_saves;
drop policy if exists "users update own save" on public.game_saves;
create policy "users read own save" on public.game_saves for select using (auth.uid()=user_id);
create policy "users insert own save" on public.game_saves for insert with check (auth.uid()=user_id);
create policy "users update own save" on public.game_saves for update using (auth.uid()=user_id) with check (auth.uid()=user_id);

create table if not exists public.promo_codes (id bigint generated by default as identity primary key, code text unique not null, amount numeric not null default 0, active boolean not null default true);
alter table public.promo_codes enable row level security;
drop policy if exists "users read active promo codes" on public.promo_codes;
create policy "users read active promo codes" on public.promo_codes for select using (active=true);

create table if not exists public.promo_redemptions (id bigint generated by default as identity primary key,user_id uuid not null references auth.users(id) on delete cascade,promo_code_id bigint not null references public.promo_codes(id) on delete cascade,redeemed_at timestamptz not null default now(),unique(user_id,promo_code_id));
alter table public.promo_redemptions enable row level security;
drop policy if exists "users read own promo redemptions" on public.promo_redemptions;
drop policy if exists "users insert own promo redemptions" on public.promo_redemptions;
create policy "users read own promo redemptions" on public.promo_redemptions for select using (auth.uid()=user_id);
create policy "users insert own promo redemptions" on public.promo_redemptions for insert with check (auth.uid()=user_id);

